def test_preview_and_selective_import_prusaslicer(client: TestClient):
    a_token = _login(client, "admin", "admin123")["access_token"]

    multi_bundle = (
        SAMPLE_BUNDLE_INI
        + "\n[filament:Prusament PETG Orange]\n"
        + "filament_type = PETG\n"
        + "filament_density = 1.27\n"
        + "filament_colour = #FF6B00\n"
        + "temperature = 240\n"
        + "bed_temperature = 80\n"
    )

    filaments_before = len(client.get("/api/admin/filaments", headers=_auth(a_token)).json())
    profiles_before = len(client.get("/api/admin/profiles", headers=_auth(a_token)).json())

    # 1. Preview returns all 4 items with metadata and creates 0 DB rows
    r_prev = client.post(
        "/api/admin/profiles/preview-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("full_export.ini", multi_bundle.encode("utf-8"), "text/plain"))],
    )
    assert r_prev.status_code == 200, r_prev.text
    prev = r_prev.json()
    assert prev["filament_count"] == 2
    assert prev["process_count"] == 1
    assert prev["machine_count"] == 1
    assert prev["skipped_count"] == 0
    assert len(prev["items"]) == 4

    by_key = {item["key"]: item for item in prev["items"]}
    assert "filament::Prusament PLA Galaxy Black" in by_key
    assert "filament::Prusament PETG Orange" in by_key
    assert "process::0.20mm SPEED MK4" in by_key
    assert "machine::Original Prusa MK4" in by_key
    assert by_key["filament::Prusament PETG Orange"]["material"] == "PETG"
    assert by_key["filament::Prusament PETG Orange"]["color_hex"] == "#FF6B00"
    assert all(not item["already_exists"] for item in prev["items"])

    assert len(client.get("/api/admin/filaments", headers=_auth(a_token)).json()) == filaments_before
    assert len(client.get("/api/admin/profiles", headers=_auth(a_token)).json()) == profiles_before

    # 2. Malformed selected_keys returns 400 INVALID_SELECTION
    r_bad = client.post(
        "/api/admin/profiles/import-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("full_export.ini", multi_bundle.encode("utf-8"), "text/plain"))],
        data={"selected_keys": "{not-a-list"},
    )
    assert r_bad.status_code == 400
    assert r_bad.json()["detail"]["code"] == "INVALID_SELECTION"

    # 3. Selective import: choose ONLY 1 filament + 1 process
    chosen = ["filament::Prusament PETG Orange", "process::0.20mm SPEED MK4"]
    r_imp = client.post(
        "/api/admin/profiles/import-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("full_export.ini", multi_bundle.encode("utf-8"), "text/plain"))],
        data={"selected_keys": json.dumps(chosen), "update_existing": "true"},
    )
    assert r_imp.status_code == 200, r_imp.text
    imp = r_imp.json()
    assert imp["filaments_created"] == 1
    assert imp["profiles_created"] == 1
    assert [f["filament"]["name"] for f in imp["filaments"]] == ["Prusament PETG Orange"]
    assert [p["profile"]["name"] for p in imp["profiles"]] == ["0.20mm SPEED MK4"]

    # Confirm unselected items were NOT created
    all_fil_names = {f["name"] for f in client.get("/api/admin/filaments", headers=_auth(a_token)).json()}
    all_prof_names = {p["name"] for p in client.get("/api/admin/profiles", headers=_auth(a_token)).json()}
    assert "Prusament PETG Orange" in all_fil_names
    assert "Prusament PLA Galaxy Black" not in all_fil_names
    assert "0.20mm SPEED MK4" in all_prof_names
    assert "Original Prusa MK4" not in all_prof_names

    # 4. Re-preview shows already_exists == True ONLY for the 2 imported items
    r_prev2 = client.post(
        "/api/admin/profiles/preview-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("full_export.ini", multi_bundle.encode("utf-8"), "text/plain"))],
    )
    assert r_prev2.status_code == 200
    by_key2 = {item["key"]: item for item in r_prev2.json()["items"]}
    assert by_key2["filament::Prusament PETG Orange"]["already_exists"] is True
    assert by_key2["process::0.20mm SPEED MK4"]["already_exists"] is True
    assert by_key2["filament::Prusament PLA Galaxy Black"]["already_exists"] is False
    assert by_key2["machine::Original Prusa MK4"]["already_exists"] is False

