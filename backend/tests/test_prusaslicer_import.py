def test_import_prusaslicer_bundle_with_inherits_and_upsert(client: TestClient):
    a_token = _login(client, "admin", "admin123")["access_token"]

    r = client.post(
        "/api/admin/profiles/import-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("prusa_bundle.ini", SAMPLE_BUNDLE_INI.encode("utf-8"), "text/plain"))],
        data={
            "import_filaments": "true",
            "import_processes": "true",
            "import_machines": "true",
            "update_existing": "true",
        },
    )
    assert r.status_code == 200, r.text
    body = r.json()
    assert body["filaments_created"] == 1
    assert body["filaments_updated"] == 0
    assert body["profiles_created"] == 2
    assert body["profiles_updated"] == 0
    assert body["skipped_count"] == 0

    fil_item = body["filaments"][0]
    assert fil_item["filament"]["name"] == "Prusament PLA Galaxy Black"
    assert fil_item["filament"]["material"] == "PLA"
    assert fil_item["filament"]["density_g_cm3"] == pytest.approx(1.25)
    assert fil_item["filament"]["color_hex"] == "#1F2937"
    assert fil_item["filament"]["filament_profile_id"] == fil_item["profile"]["id"]

    with database.SessionLocal() as db:
        fil_prof = db.get(OrcaProfile, fil_item["profile"]["id"])
        assert fil_prof is not None
        fil_json = json.loads(Path(fil_prof.file_path).read_text(encoding="utf-8"))
        assert fil_json["nozzle_temperature"] == ["215"]
        assert fil_json["textured_plate_temp"] == ["60"]
        assert "\n" in fil_json["filament_start_gcode"][0]

        proc_item = next(p for p in body["profiles"] if p["profile"]["kind"] == "process")
        proc_prof = db.get(OrcaProfile, proc_item["profile"]["id"])
        proc_json = json.loads(Path(proc_prof.file_path).read_text(encoding="utf-8"))
        assert proc_json["layer_height"] == "0.2"
        assert proc_json["wall_loops"] == "3"
        assert proc_json["sparse_infill_density"] == "20%"

        mach_item = next(p for p in body["profiles"] if p["profile"]["kind"] == "machine")
        mach_prof = db.get(OrcaProfile, mach_item["profile"]["id"])
        mach_json = json.loads(Path(mach_prof.file_path).read_text(encoding="utf-8"))
        assert mach_json["printable_area"] == ["0x0", "250x0", "250x210", "0x210"]
        assert mach_json["printable_height"] == "220"
        assert mach_json["machine_start_gcode"] == "G28 W\nG29"

    r_upd = client.post(
        "/api/admin/profiles/import-prusaslicer",
        headers=_auth(a_token),
        files=[("files", ("prusa_bundle.ini", SAMPLE_BUNDLE_INI.encode("utf-8"), "text/plain"))],
        data={"update_existing": "true"},
    )
    assert r_upd.status_code == 200
    assert r_upd.json()["filaments_updated"] == 1
    assert r_upd.json()["profiles_updated"] == 2
    assert r_upd.json()["filaments_created"] == 0
    assert r_upd.json()["profiles_created"] == 0


def test_import_flat_ini_zip_selective_flags_and_skipped(client: TestClient):
    a_token = _login(client, "admin", "admin123")["access_token"]

    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        zf.writestr("mk4_petg_flat.ini", SAMPLE_FLAT_INI.encode("utf-8"))
        zf.writestr("empty.ini", b"# just a comment\n")
    zip_bytes = buf.getvalue()

    r = client.post(
        "/api/admin/profiles/import-prusaslicer",
        headers=_auth(a_token),
        files=[
            ("files", ("configs.zip", zip_bytes, "application/zip")),
            ("files", ("not_an_ini.txt", b"hello", "text/plain")),
        ],
        data={
            "import_filaments": "true",
            "import_processes": "true",
            "import_machines": "false",
            "update_existing": "true",
        },
    )
    assert r.status_code == 200, r.text
    data = r.json()
    assert data["filaments_created"] == 1
    assert data["filaments"][0]["filament"]["material"] == "PETG"
    assert data["filaments"][0]["filament"]["color_hex"] == "#0EA5E9"
    assert data["profiles_created"] == 1
    assert data["profiles"][0]["profile"]["kind"] == "process"
    assert data["skipped_count"] == 2
    skipped_names = {s["filename"] for s in data["skipped"]}
    assert skipped_names == {"empty.ini", "not_an_ini.txt"}


