import * as THREE from 'three';
import { describe, expect, it } from 'vitest';
import {
  FEATURE_COLORS,
  GCODE_FEATURE_ORDER,
  GcodePreviewRenderer,
  parseGcode,
  type GcodeFeatureType,
} from '../gcodePreview';

describe('parseGcode', () => {
  it('parses OrcaSlicer G-code with front-left bed origin, printable_area, and G2/G3 arcs', () => {
    const orcaGcode = `
; printable_area = 0x0,300x0,300x300,0x300
; layer_height = 0.20
G90
M83
;LAYER_CHANGE
;Z:0.200
G0 F6000 X140 Y140 Z0.200
;TYPE:Skirt
G1 F1800 X160 Y140 E1.2
;TYPE:Outer wall
G1 X160 Y160 E1.2
G3 X140 Y160 I-10 J0 E1.5
;TYPE:Inner wall
G1 X142 Y142 E0.9
;LAYER_CHANGE
;Z:0.400
G0 X145 Y145 Z0.400
;TYPE:Sparse infill
G1 X155 Y155 E0.8
;TYPE:Support
G1 X130 Y130 E0.5
M84
`;

    const parsed = parseGcode(orcaGcode, { bedX: 300, bedY: 300 });
    expect(parsed.layerCount).toBe(2);
    expect(parsed.layerHeightMm).toBeCloseTo(0.2, 2);
    expect(parsed.presentFeatures).toContain('skirt_brim');
    expect(parsed.presentFeatures).toContain('outer_wall');
    expect(parsed.presentFeatures).toContain('inner_wall');
    expect(parsed.presentFeatures).toContain('sparse_infill');
    expect(parsed.presentFeatures).toContain('support');

    // G3 arc should tessellate into multiple extrusion segments
    expect(parsed.featureSegmentCounts.outer_wall).toBeGreaterThan(4);
    expect(parsed.totalTravelSegments).toBeGreaterThanOrEqual(2);

    // Coordinates should be shifted from [0..300] to [-150..+150]
    expect(parsed.bounds.minX).toBeLessThan(0);
    expect(parsed.bounds.maxX).toBeGreaterThan(0);
    expect(parsed.bounds.minX).toBeCloseTo(-20, 1);
    expect(parsed.bounds.maxX).toBeCloseTo(10, 1);
  });

  it('parses MockTrimeshSlicer G-code with centered origin and M82 absolute extrusion', () => {
    const mockGcode = `
; generated by Print-Web MockTrimeshSlicer
; printweb_coord_origin = center
; layer_height = 0.20
G90
M82
;LAYER_CHANGE
;Z:0.200
G0 Z0.200 F600
;TYPE:Outer wall
G0 F6000 X-10.000 Y-10.000
G1 F1800 X10.000 Y-10.000 E1.0000
G1 F1800 X10.000 Y10.000 E2.0000
G1 F1800 X-10.000 Y10.000 E3.0000
G1 F1800 X-10.000 Y-10.000 E4.0000
;TYPE:Bottom surface
G0 F6000 X-8.000 Y-8.000
G1 F1800 X8.000 Y8.000 E4.8000
M84
`;

    const parsed = parseGcode(mockGcode, { bedX: 250, bedY: 220 });
    expect(parsed.layerCount).toBe(1);
    expect(parsed.featureSegmentCounts.outer_wall).toBe(4);
    expect(parsed.featureSegmentCounts.solid_infill).toBe(1);
    expect(parsed.bounds.minX).toBeCloseTo(-10, 2);
    expect(parsed.bounds.maxX).toBeCloseTo(10, 2);
    expect(parsed.layers[0].endByFeature.outer_wall).toBe(4);
    expect(parsed.layers[0].endByFeature.solid_infill).toBe(5 - 4);
  });

  it('parses ;WIDTH:, ;HEIGHT:, and feedrate F in mm/s with sensible defaults', () => {
    const gcode = `
; printable_area = 0x0,200x0,200x200,0x200
; layer_height = 0.20
G90
M83
;LAYER_CHANGE
;Z:0.200
G0 X90 Y90 Z0.200
;TYPE:Outer wall
; default width ~0.42, default height = 0.20, default speed = 60 mm/s
G1 X110 Y90 E1.0
;WIDTH:0.65
;HEIGHT:0.28
;TYPE:Inner wall
G1 F3000
G1 X110 Y110 E1.2
;WIDTH:0.38
;HEIGHT:0.16
;TYPE:Sparse infill
G1 F9000 X90 Y110 E1.4
`;

    const parsed = parseGcode(gcode, { bedX: 200, bedY: 200 });
    expect(parsed.speedRange.minMmS).toBeCloseTo(50, 1);
    expect(parsed.speedRange.maxMmS).toBeCloseTo(150, 1);

    const outerProps = parsed.extrusionPropsByFeature?.outer_wall;
    expect(outerProps).toBeDefined();
    expect(outerProps![0]).toBeCloseTo(0.42, 2);
    expect(outerProps![1]).toBeCloseTo(0.2, 2);
    expect(outerProps![2]).toBeCloseTo(60, 1);

    const innerProps = parsed.extrusionPropsByFeature?.inner_wall;
    expect(innerProps).toBeDefined();
    expect(innerProps![0]).toBeCloseTo(0.65, 2);
    expect(innerProps![1]).toBeCloseTo(0.2, 2); // z=0.20 -> clamped so bead bottom stays >= 0
    expect(innerProps![2]).toBeCloseTo(50, 1);

    const infillProps = parsed.extrusionPropsByFeature?.sparse_infill;
    expect(infillProps).toBeDefined();
    expect(infillProps![0]).toBeCloseTo(0.38, 2);
    expect(infillProps![1]).toBeCloseTo(0.16, 2);
    expect(infillProps![2]).toBeCloseTo(150, 1);
  });

  it('filters out start purge lines, out-of-bed wipe moves, and end-gcode moves while honoring trailing config block', () => {
    const gcode = `
G90
M83
; Start purge line before first LAYER_CHANGE
G0 F6000 X5 Y5 Z0.28
G1 F1500 X240 Y5 E12.0
G1 F1500 X240 Y6 E0.2
G1 F1500 X5 Y6 E12.0
;LAYER_CHANGE
;Z:0.20
;HEIGHT:0.20
G0 F9000 X120 Y120 Z0.20
;TYPE:Outer wall
;WIDTH:0.42
G1 F2400 X140 Y120 E1.0
G1 X140 Y140 E1.0
G1 X120 Y140 E1.0
G1 X120 Y120 E1.0
; Out-of-bed nozzle wipe move during print
G0 F9000 X-10 Y310
G1 F3000 X10 Y310 E0.5
; End G-code markers
M104 S0
G0 F6000 X0 Y240
G1 F1200 X20 Y240 E2.0
M84
; CONFIG_BLOCK_START
; layer_height = 0.20
; printable_area = 0x0,250x0,250x250,0x250
; CONFIG_BLOCK_END
`;

    const parsed = parseGcode(gcode, { bedX: 250, bedY: 250 });
    expect(parsed.layerCount).toBe(1);
    expect(parsed.totalExtrusionSegments).toBe(4);
    expect(parsed.featureSegmentCounts.outer_wall).toBe(4);
    // Centered around 250x250 -> [120..140] shifts to [-5..+15]
    expect(parsed.bounds.minX).toBeCloseTo(-5, 2);
    expect(parsed.bounds.maxX).toBeCloseTo(15, 2);
    expect(parsed.bounds.minY).toBeCloseTo(-5, 2);
    expect(parsed.bounds.maxY).toBeCloseTo(15, 2);
  });

  it('computes featureStats segment counts, extrusion lengths, and sharePct summing to ~100%', () => {
    const gcode = `
; printable_area = 0x0,200x0,200x200,0x200
; layer_height = 0.20
G90
M83
;LAYER_CHANGE
;Z:0.20
G0 X80 Y80 Z0.20
;TYPE:Outer wall
G1 F2400 X120 Y80 E2.0
;TYPE:Inner wall
G1 F3600 X120 Y100 E1.0
;TYPE:Sparse infill
G1 F6000 X80 Y100 E2.0
`;

    const parsed = parseGcode(gcode, { bedX: 200, bedY: 200 });
    // Lengths: outer_wall = 40mm, inner_wall = 20mm, sparse_infill = 40mm -> total = 100mm
    expect(parsed.featureStats.outer_wall).toEqual({
      segmentCount: 1,
      lengthMm: 40,
      sharePct: 40,
    });
    expect(parsed.featureStats.inner_wall).toEqual({
      segmentCount: 1,
      lengthMm: 20,
      sharePct: 20,
    });
    expect(parsed.featureStats.sparse_infill).toEqual({
      segmentCount: 1,
      lengthMm: 40,
      sharePct: 40,
    });
    expect(parsed.featureStats.support).toEqual({
      segmentCount: 0,
      lengthMm: 0,
      sharePct: 0,
    });

    const totalShare = GCODE_FEATURE_ORDER.reduce(
      (sum, feat) => sum + parsed.featureStats[feat].sharePct,
      0
    );
    expect(totalShare).toBeCloseTo(100, 1);
  });

  it('computes 5th-95th percentile speedRange on dense toolpaths to resist outlier spikes', () => {
    const lines: string[] = [
      '; printable_area = 0x0,200x0,200x200,0x200',
      '; layer_height = 0.20',
      'G90',
      'M83',
      ';LAYER_CHANGE',
      ';Z:0.20',
      'G0 X50 Y50 Z0.20',
      ';TYPE:Outer wall',
      'G1 F300 X52 Y50 E0.1', // 5 mm/s low outlier
    ];
    for (let i = 0; i < 40; i++) {
      const x = 52 + ((i % 2) === 0 ? 20 : 0);
      const y = 50 + i * 0.5;
      const feed = i < 20 ? 2400 : 7200; // 40 mm/s and 120 mm/s
      lines.push(`G1 F${feed} X${x} Y${y} E0.5`);
    }
    lines.push('G1 F24000 X80 Y80 E0.2'); // 400 mm/s high outlier

    const parsed = parseGcode(lines.join('\n'), { bedX: 200, bedY: 200 });
    expect(parsed.speedRange.minMmS).toBeCloseTo(40, 1);
    expect(parsed.speedRange.maxMmS).toBeCloseTo(120, 1);
  });

  it('maps all OrcaSlicer ;TYPE: and ;FEATURE: labels accurately into GcodeFeatureType', () => {
    const expectedMappings: Array<[string, GcodeFeatureType]> = [
      [';TYPE:Outer wall', 'outer_wall'],
      [';TYPE:Inner wall', 'inner_wall'],
      [';TYPE:Overhang wall', 'overhang_bridge'],
      [';TYPE:Bridge', 'overhang_bridge'],
      [';TYPE:Sparse infill', 'sparse_infill'],
      [';TYPE:Internal solid infill', 'solid_infill'],
      [';TYPE:Top surface', 'solid_infill'],
      [';TYPE:Bottom surface', 'solid_infill'],
      [';TYPE:Support', 'support'],
      [';TYPE:Support interface', 'support'],
      [';TYPE:Support transition', 'support'],
      [';TYPE:Skirt', 'skirt_brim'],
      [';TYPE:Brim', 'skirt_brim'],
      [';TYPE:Gap infill', 'inner_wall'],
      [';FEATURE:Prime tower', 'skirt_brim'],
      [';FEATURE:Custom', 'other'],
    ];

    const lines: string[] = [
      '; printable_area = 0x0,200x0,200x200,0x200',
      '; layer_height = 0.20',
      'G90',
      'M83',
      ';LAYER_CHANGE',
      ';Z:0.20',
      'G0 X50 Y50 Z0.20',
    ];

    expectedMappings.forEach(([directive], idx) => {
      lines.push(directive);
      lines.push(`G1 F2400 X${52 + idx * 2} Y${50 + idx} E0.5`);
    });

    const parsed = parseGcode(lines.join('\n'), { bedX: 200, bedY: 200 });

    const expectedCounts: Record<GcodeFeatureType, number> = {
      outer_wall: 1,
      inner_wall: 2, // Inner wall + Gap infill
      overhang_bridge: 2, // Overhang wall + Bridge
      sparse_infill: 1,
      solid_infill: 3, // Internal solid infill + Top surface + Bottom surface
      support: 3, // Support + Support interface + Support transition
      skirt_brim: 3, // Skirt + Brim + Prime tower
      other: 1, // Custom
    };

    for (const feat of GCODE_FEATURE_ORDER) {
      expect(parsed.featureSegmentCounts[feat]).toBe(expectedCounts[feat]);
      expect(FEATURE_COLORS[feat]).toMatch(/^#[0-9A-Fa-f]{6}$/);
    }
  });
});

describe('GcodePreviewRenderer', () => {
  it('renders GPU-instanced volumetric beads, supports O(1) scrubbing, and switches all 3 color modes', () => {
    const gcode = `
; printable_area = 0x0,200x0,200x200,0x200
; layer_height = 0.20
G90
M83
;LAYER_CHANGE
;Z:0.20
G0 F6000 X90 Y90 Z0.20
;TYPE:Outer wall
;WIDTH:0.45
;HEIGHT:0.20
G1 F1800 X110 Y90 E1.0
G1 F3600 X110 Y110 E1.0
;LAYER_CHANGE
;Z:0.40
G0 F6000 X90 Y90 Z0.40
;TYPE:Sparse infill
;WIDTH:0.48
G1 F7200 X110 Y110 E1.2
`;

    const parsed = parseGcode(gcode, { bedX: 200, bedY: 200 });
    const renderer = new GcodePreviewRenderer();
    renderer.load(parsed, '#FF5500');

    const meshes = renderer.group.children.filter(
      (c): c is THREE.Mesh => c instanceof THREE.Mesh && c.geometry instanceof THREE.InstancedBufferGeometry
    );
    expect(meshes.length).toBe(2); // outer_wall + sparse_infill

    for (const mesh of meshes) {
      const geo = mesh.geometry as THREE.InstancedBufferGeometry;
      expect(geo.getAttribute('aStart')).toBeDefined();
      expect(geo.getAttribute('aEnd')).toBeDefined();
      expect(geo.getAttribute('aWidth')).toBeDefined();
      expect(geo.getAttribute('aHeight')).toBeDefined();
      expect(geo.getAttribute('aSpeed')).toBeDefined();
    }

    // Layer 0 full range: outer_wall=2, sparse_infill=0
    renderer.setRange(0, parsed.layers[0].moveCount, false);
    const outerMesh = meshes.find((m) => (m.geometry as THREE.InstancedBufferGeometry).instanceCount === 2);
    const infillMesh = meshes.find((m) => (m.geometry as THREE.InstancedBufferGeometry).instanceCount === 0);
    expect(outerMesh).toBeDefined();
    expect(infillMesh).toBeDefined();

    // Partial scrub on layer 0: move 2 (0=travel, 1=first outer_wall, 2=second outer_wall)
    renderer.setRange(0, 2, true);
    expect((outerMesh!.geometry as THREE.InstancedBufferGeometry).instanceCount).toBe(1);

    // Switch color modes
    renderer.setColorMode('speed', '#FF5500');
    expect((outerMesh!.material as THREE.ShaderMaterial).uniforms.uColorMode.value).toBe(2);
    renderer.setColorMode('filament', '#123456');
    expect((outerMesh!.material as THREE.ShaderMaterial).uniforms.uColorMode.value).toBe(1);
    expect((outerMesh!.material as THREE.ShaderMaterial).uniforms.uBaseColor.value.getHexString()).toBe('123456');
    renderer.setColorMode('line-type', '#123456');
    expect((outerMesh!.material as THREE.ShaderMaterial).uniforms.uColorMode.value).toBe(0);

    // Feature visibility
    renderer.setVisibleFeatures(new Set<GcodeFeatureType>(['sparse_infill']), true);
    expect(infillMesh!.visible).toBe(false);
    expect(outerMesh!.visible).toBe(true);

    renderer.dispose();
    expect(renderer.group.children.length).toBe(1); // only nozzleGroup remains
  });
});
